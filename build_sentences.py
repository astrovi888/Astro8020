#!/usr/bin/env python3
"""Build data-bulk.js: example sentences from Tatoeba (via ManyThings deu-eng, CC BY 2.0 FR)
that use ONLY words from the top-1000 list in data-words.js.
Usage: python3 build_sentences.py deu.txt lemma.txt data-words.js data-bulk.js"""
import re, sys, random, math, json

deu, lem, words, out = sys.argv[1:5]
PER_BAND = 160
LV = {1: "A1", 2: "A2", 3: "B1", 4: "B2"}
BAD = ("scheiß", "arsch", "fick", "fotze", "hure", "nazi", "mord", "töte", "erschieß", "umbring",
       "vergewalt", "porno", "sex", "leiche", "selbstmord", "hitler")

# 1) rank + CEFR level of every word in the top-1000 list (line number = rank)
body = open(words, encoding="utf8").read().split("const W1=`", 1)[1].split("`", 1)[0].strip("\n").split("\n")
rank = {}
for k, line in enumerate(body, 1):
    if line == "-":
        continue
    a, _en, c = line.split("|")
    w = re.sub(r"^(der|die|das) ", "", a) if c[0] == "n" else a
    rank.setdefault(w.lower(), (k, int(c[1])))

# 2) inflected form -> lemma(s); auto-detect column order
def load_lemma(swap):
    m = {}
    for line in open(lem, encoding="utf8", errors="ignore"):
        p = line.rstrip("\n").split("\t")
        if len(p) < 2 or p[0].startswith("#"):
            continue
        infl, lemma = (p[1], p[0]) if swap else (p[0], p[1])
        m.setdefault(infl.lower(), set()).add(lemma.lower())
    return m

lm = load_lemma(False)
if "gehen" not in lm.get("ging", set()):
    lm = load_lemma(True)
print("lemma forms loaded:", len(lm), "| ging ->", sorted(lm.get("ging", [])))

def info(tok):
    t = tok.lower()
    best = None
    for c in {t} | lm.get(t, set()):
        if c in rank and (best is None or rank[c][0] < best[0]):
            best = rank[c]
    return best

# 3) filter sentences
rows, seen = [], set()
for line in open(deu, encoding="utf8", errors="ignore"):
    p = line.rstrip("\n").split("\t")
    if len(p) < 2:
        continue
    en, de = p[0].strip(), p[1].strip()
    toks = re.findall(r"[A-Za-zÄÖÜäöüß]+", de)
    low = de.lower()
    if low in seen or not (4 <= len(toks) <= 10):
        continue
    if not de[0].isupper() or de[-1] not in ".?!" or not en or en[-1] not in ".?!":
        continue
    if re.search(r"[\d\"„“«»()]", de) or any(b in low for b in BAD):
        continue
    if not 0.4 < len(en) / len(de) < 2.5:
        continue
    infos = [info(t) for t in toks]
    if any(i is None for i in infos):
        continue
    seen.add(low)
    rows.append([de, en, math.ceil(max(i[0] for i in infos) / 100) * 100, LV[max(i[1] for i in infos)], "Daily", ""])

# 4) balance across frequency bands and write
by = {}
for r in rows:
    by.setdefault(r[2], []).append(r)
random.seed(8020)
sel = []
for b in sorted(by):
    random.shuffle(by[b])
    sel += sorted(by[b][:PER_BAND], key=lambda r: len(r[0]))
head = "// Generated by build_sentences.py from Tatoeba (CC BY 2.0 FR) via ManyThings. Do not edit by hand.\n"
open(out, "w", encoding="utf8").write(head + "const BULK=" + json.dumps(sel, ensure_ascii=False) + ";\n")
print(len(sel), "sentences written;", "available per band:", {b: len(v) for b, v in sorted(by.items())})
